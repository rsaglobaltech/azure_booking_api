-- ============================================================================
-- Mapping Tables for Multi-Tenant and Friendly Names: Oracle Migration
-- ============================================================================

CREATE TABLE agency_mapping (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    friendly_name VARCHAR2(255) UNIQUE NOT NULL,
    ms_tenant_id VARCHAR2(255) NOT NULL,
    ms_business_id VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE staff_mapping (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id NUMBER NOT NULL,
    friendly_name VARCHAR2(255) NOT NULL,
    ms_staff_member_id VARCHAR2(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_staff_agency FOREIGN KEY (agency_id) REFERENCES agency_mapping(id) ON DELETE CASCADE,
    CONSTRAINT uq_agency_friendly_name UNIQUE(agency_id, friendly_name)
);
